"""Manifeste des banques expressives : un fichier TypeScript par banque dans src/audio/expressive/.

Partagé par tools/build-expressive-banks.py (écriture) et tools/check-expressive-banks.py (lecture).
Chaque fichier de banque contient un objet JSON valide (un échantillon par ligne), relu tel quel ici.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / 'src/audio/expressive'
INDEX = ROOT / 'src/audio/expressive-manifest.ts'
HEADER = '// Generated by tools/build-expressive-banks.py; do not edit sample metadata.\n'


def ident(bank):
    return ''.join(part.capitalize() for part in bank.split('_'))


def bank_json(definition):
    lines = ['{', f'  "kind": {json.dumps(definition["kind"])},']
    if 'velocityEnds' in definition:
        lines.append(f'  "velocityEnds": {json.dumps(definition["velocityEnds"])},')
    lines.append('  "samples": [')
    rows = [json.dumps(s) for s in definition['samples']]
    lines += [f'    {r},' for r in rows[:-1]] + ([f'    {rows[-1]}'] if rows else [])
    lines += ['  ]', '}']
    return '\n'.join(lines)


def write_manifest(banks):
    DIR.mkdir(parents=True, exist_ok=True)
    (DIR / 'types.ts').write_text(
        HEADER
        + 'export interface ExpressiveEntry { key: number; layer: number; rr: number; file: string; off: number; gain: number; lo?: number; hi?: number; tune?: number }\n'
        + "export interface ExpressiveBank { kind: 'instrument' | 'drums'; velocityEnds?: number[]; samples: ExpressiveEntry[] }\n")
    for bank, definition in banks.items():
        (DIR / f'{bank}.ts').write_text(
            HEADER + "import type { ExpressiveBank } from './types';\n\n"
            + f'const bank: ExpressiveBank = {bank_json(definition)};\nexport default bank;\n')
    imports = ''.join(f"import {ident(b)} from './expressive/{b}';\n" for b in banks)
    INDEX.write_text(
        HEADER + "import type { ExpressiveBank } from './expressive/types';\n" + imports
        + "export type { ExpressiveBank, ExpressiveEntry } from './expressive/types';\n\n"
        + '/** Banques expressives (nuances et répétitions réellement enregistrées), une par fichier dans ./expressive. */\n'
        + 'export const EXPRESSIVE: Record<string, ExpressiveBank> = {\n'
        + ''.join(f'  {b}: {ident(b)},\n' for b in banks) + '};\n')


def read_manifest():
    banks = {}
    for line in INDEX.read_text().splitlines():
        if line.startswith('import ') and "'./expressive/" in line and 'type' not in line.split()[1]:
            bank = line.rsplit('/', 1)[1].rstrip("';")
            text = (DIR / f'{bank}.ts').read_text()
            body = text.split('const bank: ExpressiveBank = ', 1)[1]
            banks[bank] = json.loads(body[:body.rindex('};') + 1])
    return banks
